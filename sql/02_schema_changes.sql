-- =====================================================================
-- 02_schema_changes.sql
-- Phase 2: the schema changes the rest of the solution depends on.
-- Every change here is documented in README.md, because Nana's team
-- maintains this schema after the engagement ends.
--
-- Guiding rule: stop NEW bad data, keep OLD bad data visible.
-- Rules are added with NOT VALID where existing rows already break
-- them: PostgreSQL then enforces the rule on every new insert/update
-- but does not reject the table because of history. The old rows stay
-- for review (see data_findings.md) instead of being silently deleted.
--
-- Run on a FRESH load only (reset.ps1). Running it twice on the same
-- database fails, because the columns and rules already exist.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. Safe ID numbering for new rows.
-- Problem: order_id, order_item_id and log_id have no default, so new
-- rows need an ID from somewhere. "SELECT max(id) + 1" is a race: two
-- buyers at the same instant read the same max and collide.
-- Fix: an IDENTITY column is backed by a sequence, which hands every
-- caller a different number even at the same instant, without locking.
-- BY DEFAULT (not ALWAYS) so existing IDs and explicit IDs still work.
-- The sequence is then moved past the highest existing ID.
-- ---------------------------------------------------------------------
ALTER TABLE orders        ALTER COLUMN order_id      ADD GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE order_items   ALTER COLUMN order_item_id ADD GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE inventory_log ALTER COLUMN log_id        ADD GENERATED BY DEFAULT AS IDENTITY;

SELECT setval(pg_get_serial_sequence('orders',        'order_id'),      (SELECT max(order_id)      FROM orders));
SELECT setval(pg_get_serial_sequence('order_items',   'order_item_id'), (SELECT max(order_item_id) FROM order_items));
SELECT setval(pg_get_serial_sequence('inventory_log', 'log_id'),        (SELECT max(log_id)        FROM inventory_log));

-- ---------------------------------------------------------------------
-- 2. Stock can never go below zero (finding F-02).
-- The safety net under place_order: even a manual UPDATE in a terminal
-- cannot push stock negative. NOT VALID because 14 products are already
-- negative; they stay visible for a stock count.
-- ---------------------------------------------------------------------
ALTER TABLE products
    ADD CONSTRAINT products_stock_not_negative CHECK (stock_quantity >= 0) NOT VALID;

-- Quantities on order lines must be positive. All existing rows already
-- pass (check C4 = 0), so this one is fully validated.
ALTER TABLE order_items
    ADD CONSTRAINT order_items_quantity_positive CHECK (quantity > 0);

-- ---------------------------------------------------------------------
-- 3. Relationships (findings F-04, F-07, F-08).
-- Foreign keys stop new rows pointing at things that do not exist.
-- NOT VALID where history already breaks the rule; fully validated
-- where the data is already clean (checks A1 and A8 found 0).
-- Default ON DELETE (NO ACTION): deleting a row that is still referenced
-- is refused, so nobody can quietly create new orphans by deleting.
-- ---------------------------------------------------------------------
ALTER TABLE products      ADD CONSTRAINT products_category_fk
    FOREIGN KEY (category_id) REFERENCES categories (category_id);
ALTER TABLE categories    ADD CONSTRAINT categories_parent_fk
    FOREIGN KEY (parent_id)   REFERENCES categories (category_id) NOT VALID;
ALTER TABLE orders        ADD CONSTRAINT orders_customer_fk
    FOREIGN KEY (customer_id) REFERENCES customers  (customer_id) NOT VALID;
ALTER TABLE order_items   ADD CONSTRAINT order_items_order_fk
    FOREIGN KEY (order_id)    REFERENCES orders     (order_id)    NOT VALID;
ALTER TABLE order_items   ADD CONSTRAINT order_items_product_fk
    FOREIGN KEY (product_id)  REFERENCES products   (product_id);
ALTER TABLE inventory_log ADD CONSTRAINT inventory_log_product_fk
    FOREIGN KEY (product_id)  REFERENCES products   (product_id)  NOT VALID;

-- ---------------------------------------------------------------------
-- 4. What each order status MEANS (finding F-01).
-- The stored status stays as the application wrote it. Reports join to
-- this table on lower(trim(status)) and use the meaning instead, so
-- 'COMPLETED', ' completed' and 'complete' all count as completed.
-- counts_as_spend is the business rule for "total spent" (assumption:
-- completed and shipped count; pending is not yet fulfilled; cancelled
-- and refunded returned the money). Changing the rule = one UPDATE here.
-- ---------------------------------------------------------------------
CREATE TABLE order_status_map (
    status_key      text PRIMARY KEY,          -- lower(trim(orders.status))
    meaning         text    NOT NULL
                    CHECK (meaning IN ('pending','shipped','completed','cancelled','refunded')),
    counts_as_spend boolean NOT NULL
);

INSERT INTO order_status_map (status_key, meaning, counts_as_spend) VALUES
    ('pending',   'pending',   false),
    ('shipped',   'shipped',   true),
    ('completed', 'completed', true),
    ('complete',  'completed', true),
    ('cancelled', 'cancelled', false),
    ('canceled',  'cancelled', false),
    ('refunded',  'refunded',  false);

COMMENT ON TABLE order_status_map IS
    'Maps every stored spelling of orders.status (after lower/trim) to one meaning. '
    'Reports use the meaning. Add a row here when the application starts writing a new spelling.';

-- Any status the map does not know would be silently left out of reports.
-- This view makes it visible instead (expected: no rows).
CREATE VIEW unmapped_order_statuses AS
SELECT o.status, count(*) AS orders
FROM   orders o
LEFT   JOIN order_status_map m ON m.status_key = lower(trim(o.status))
WHERE  m.status_key IS NULL
GROUP  BY o.status;